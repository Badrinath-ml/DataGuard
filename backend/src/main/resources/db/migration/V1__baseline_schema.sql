-- Idempotent baseline migration for fresh PostgreSQL databases and existing JPA-created schemas.
-- It only adds missing schema objects/columns and never drops application data.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255),
    email VARCHAR(255),
    password VARCHAR(255),
    role VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    technology VARCHAR(255),
    user_id BIGINT,
    created_at TIMESTAMP,
    last_quality_score INTEGER,
    CONSTRAINT fk_projects_user_id FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT,
    quality_score INTEGER,
    review_date TIMESTAMP,
    CONSTRAINT fk_reviews_project_id FOREIGN KEY (project_id) REFERENCES projects(id)
);

CREATE TABLE IF NOT EXISTS findings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT,
    category VARCHAR(255),
    severity VARCHAR(255),
    title VARCHAR(255),
    file_path VARCHAR(255),
    line_number INTEGER,
    evidence VARCHAR(2000),
    recommendation VARCHAR(2000),
    status VARCHAR(255),
    CONSTRAINT fk_findings_review_id FOREIGN KEY (review_id) REFERENCES reviews(id)
);

CREATE TABLE IF NOT EXISTS ai_explanations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finding_id BIGINT UNIQUE,
    explanation TEXT,
    impact TEXT,
    recommended_action TEXT,
    CONSTRAINT fk_ai_explanations_finding_id FOREIGN KEY (finding_id) REFERENCES findings(id)
);

CREATE TABLE IF NOT EXISTS ai_conversation_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL UNIQUE,
    user_id BIGINT NOT NULL,
    review_id BIGINT,
    context_type VARCHAR(24) NOT NULL DEFAULT 'CODE_CHECK',
    title VARCHAR(180) NOT NULL DEFAULT 'New scan',
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ai_sessions_user_id FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_ai_sessions_review_id FOREIGN KEY (review_id) REFERENCES reviews(id)
);

CREATE TABLE IF NOT EXISTS ai_conversation_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL,
    role VARCHAR(20) NOT NULL,
    content TEXT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ai_messages_session_id FOREIGN KEY (session_id) REFERENCES ai_conversation_sessions(id)
);

